import { wallToUtc, offsetAt } from './ref.mjs';
const iso = ms => new Date(ms).toISOString();
const pad = (n, w = 2) => String(n).padStart(w, '0');

function row(y, mo, d, h, mi, s = 0) {
  const r = wallToUtc(y, mo, d, h, mi, s);
  // 후보 개수 재계산
  const naive = Date.UTC(y, mo - 1, d, h, mi, s);
  const seen = new Set(); let n = 0;
  for (const off of [507.8667, 510, 540, 570, 600]) {
    const c = naive - Math.round(off * 60000);
    if (seen.has(c)) continue; seen.add(c);
    if (Math.abs(offsetAt(c).total - off) < 1e-6) n++;
  }
  const wall = `${y}-${pad(mo)}-${pad(d)} ${pad(h)}:${pad(mi)}:${pad(s)}`;
  return `| ${wall} | ${iso(r.utc)} | ${r.off} | ${n} | ${r.flags.join(',') || '—'} |`;
}

function block(title, rows) {
  console.log(`\n### ${title}`);
  console.log('| 입력 벽시계(KR) | 채택 UTC | 총오프셋(분) | 후보수 | 플래그 |');
  console.log('|---|---|---|---|---|');
  for (const r of rows) console.log(row(...r));
}

