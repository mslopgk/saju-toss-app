/**
 * 화면에 나가는 문장에서 엠대시를 없앤다.
 *
 * ## 왜 데이터가 아니라 출력 경계에서 고치나
 * 엠대시는 지식베이스의 **구조 구분자**다. 카드 198장 중 156장의 제목이 `라벨 — 값` 모양이고
 * `template.ts` 가 `split(' — ')` 로 그 문법을 읽는다. 데이터를 치환하면 파서가 깨진다.
 *
 * 그래서 파싱은 그대로 두고, **사람이 읽는 문자열이 만들어지는 마지막 지점**에서만 바꾼다.
 *
 * ## 왜 없애나
 * 엠대시는 LLM 이 쓴 글의 가장 흔한 서명이고, 한국어 문장에서는 콜론이나 마침표가
 * 같은 일을 더 조용히 한다. 측정해 보니 화면 문자열 52개 중 12개에 들어 있었다
 * (근거: `design-taste-frontend` 스킬 §9.G).
 *
 * ## 규칙
 * - `라벨 — 값` → `라벨: 값` — 한국어에서 가장 자연스럽게 읽히는 대체다.
 * - 문장을 잇는 자리의 엠대시는 이 함수가 손대지 않는다. 콜론으로 바꾸면 어색해지므로
 *   **문장 틀에서 직접** 마침표나 쉼표로 고친다.
 */

/** ` — ` 를 콜론으로. 이미 콜론·마침표가 앞에 있으면 중복을 만들지 않는다. */
export function labelColon(text: string): string {
  return text.replace(/\s*[—–]\s*/g, (_match, offset: number) => {
    const before = text.slice(0, offset).trimEnd()
    return /[:.,·]$/.test(before) ? ' ' : ': '
  })
}
