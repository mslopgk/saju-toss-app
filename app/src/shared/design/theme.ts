/**
 * 디자인 토큰 — 먹과 인주.
 *
 * ## 두 번의 실패에서 나온 방향
 * 1판: 네이비-퍼플 그라디언트 + 글래스 카드 + 발광 후광. 생성 모델이 "어두운 앱"을 요청받으면
 *      기본으로 뱉는 조합 그대로였다.
 * 2판: 그걸 걷어내고 무채색 미니멀로 갔다. 깔끔해졌지만 **관점이 없었다** — 장식 과다에서
 *      반대편 기본값으로 옮긴 것에 불과했다.
 *
 * 3판(지금)은 관점을 정한다. 사주는 먹으로 쓴 글이고 도장으로 맺는다. 바탕은 먹, 강조는
 * 인주(印朱) 하나, 질감은 종이. 오행은 색이 아니라 **그림과 이름**으로 말한다.
 *
 * ## 지키는 규칙
 * 1. **강조색은 인주 하나.** 화면마다 색이 달라지지 않는다(1·2판은 사용자의 오행에 따라
 *    강조색이 바뀌어서, 火 사용자에게는 주황 버튼이 생기고 그게 경고처럼 읽혔다).
 *    오행 정체성은 오브젝트 그림과 이름표가 이미 말한다.
 *    근거: `design-taste-frontend` §4.2 Color Consistency Lock.
 * 2. **라운드는 하나의 규칙.** 누르는 것 12, 면 16, 배지 999, 막대 2. 감사해 보니 9종이
 *    섞여 있었다. 근거: 같은 스킬 §4.4 Shape Consistency Lock.
 * 3. **테두리를 쓰지 않는다.** 어두운 바탕 위 반투명 테두리가 글래스모피즘의 서명이다.
 * 4. **스케일 밖의 숫자를 쓰지 않는다.**
 */

