/**
 * 디자인 토큰.
 *
 * ## 앞 판이 왜 "AI 스러웠나"
 * 네이비-퍼플 그라디언트 + 반투명 글래스 카드 + 발광 후광 + 글로우 그림자.
 * 생성 모델이 "어두운 앱" 을 요청받으면 기본으로 뱉는 조합 그대로였다. 게다가 장식이 동시에
 * 다 켜져 있어서(배경 이미지 + 그라디언트 + 후광 + 테두리 + 글로우) 화면이 난잡했고,
 * 배경 이미지의 보라·주황 구름이 **글자 뒤에서 얼룩**을 만들어 대비까지 깎았다.
 *
 * 이번 판이 지키는 것 넷:
 *   1. **바탕은 거의 검정이다.** 색조를 띤 어두운 배경(네이비·퍼플)이 그 티의 절반이다.
 *   2. **강조색은 화면당 하나, 한 군데.** 가장 강한 오행 막대에만 쓴다. CTA 는 흰색이다 —
 *      큰 주황 버튼은 경고처럼 읽힌다.
 *   3. **테두리를 쓰지 않는다.** 어두운 바탕 위 반투명 테두리가 글래스모피즘의 핵심 신호다.
 *      면(surface)만으로 층을 만든다.
 *   4. **스케일 밖의 숫자를 쓰지 않는다.** 앞 판은 `Spacing size={20|26|28|32}` 과
 *      `fontSize: 13|14|15|16|19|22|24|44` 가 인라인으로 흩어져 위계가 없었다.
 */

